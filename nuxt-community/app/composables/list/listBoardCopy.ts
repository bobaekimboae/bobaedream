function fallbackStats(label: string) {
  let value = 0
  for (let index = 0; index < label.length; index += 1) value += label.charCodeAt(index)
  const subscribers = (4.2 + (value % 94) / 10).toFixed(1)
  const posts = 320 + (value % 681)
  return '팔로워 ' + subscribers + '만명 · 게시물 ' + posts.toLocaleString('ko-KR') + '개'
}
