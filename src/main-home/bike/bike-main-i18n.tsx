export const localizeBikeBrand = (name: string, locale: BikeLocale) => brandNames[name]?.[locale] ?? name;

export const readBikeLocale = (): BikeLocale => {
  if (typeof window === "undefined") return "ko";
  const query = new URLSearchParams(window.location.search).get("lang");
  if (bikeLocaleOptions.some(({ id }) => id === query)) return query as BikeLocale;
  const saved = window.localStorage.getItem("bbm-bike-language");
  if (bikeLocaleOptions.some(({ id }) => id === saved)) return saved as BikeLocale;
  return "ko";
};

